import json
import re

from indiafacts.cli import main
from indiafacts.llm import LLMResult
from indiafacts.render import DISCLAIMER
from tests.fakes import FakeClient
from tests.fixtures.reliance_quarterly import INFO, QUARTERLY
from tests.test_htmlreport import NSE_CSV, SYMS, prices_for
from tests.test_nsefiling import HTML as FILING_HTML

INFO2 = {**INFO, "industry": "Refining"}


class AdaptiveLLM:
    provider, model = "fake", "m1"

    def __init__(self):
        self.calls = 0

    def complete(self, system, user, max_tokens):
        self.calls += 1
        ids = re.findall(r"^(F\d+) ", user, re.M)
        return LLMResult(json.dumps({
            "summary": "The company has a mixed picture with some gaps.", "uncertainty": "Several items are missing.",
            "claims": [{"type": "fact", "text": "The score is listed in the digest.", "ids": ids[:1]},
                       {"type": "inference", "text": "Some checks did not pass.", "ids": ids[1:3]}]}), 900, 120)


def run(tmp_path, capsys, *extra, llm=None, html=None):
    c = tmp_path / "ind.csv"
    c.write_text(NSE_CSV, encoding="utf-8")
    f = tmp_path / "f.html"
    f.write_text(FILING_HTML, encoding="utf-8")
    argv = ["RELIANCE.NS", "--score", "--universe", str(c), "--filing", str(f), "--no-tej", *extra]
    if html:
        argv += ["--html", str(html)]
    code = main(argv, client=FakeClient(stmt=QUARTERLY, info=INFO2), sleep=lambda s: None, price_client=prices_for(SYMS),
                llm_client=llm)
    out = capsys.readouterr()
    return code, out.out, out.err


def test_explain_flag_prints_template_explanation_with_ids_triggers_and_uncertainty(tmp_path, capsys):
    code, out, err = run(tmp_path, capsys, "--explain")
    block = out.split("EXPLANATION")[1].split("PROFILE")[0] if "PROFILE" in out.split("EXPLANATION")[1] else out.split("EXPLANATION")[1]
    assert code == 0 and "generated by template" in out
    assert re.search(r"\[(fact|inference)[^\]]*F\d+", block) and "WHAT WOULD CHANGE" in out and "UNCERTAINTY" in out
    assert "Evidence index" in out and DISCLAIMER in out
    assert not re.search(r"\b(buy|sell)\b", out.lower())
    assert "tokens: digest" in out and "no LLM call" in out


def test_llm_client_output_is_validated_labelled_and_token_counted(tmp_path, capsys, monkeypatch):
    llm = AdaptiveLLM()
    code, out, err = run(tmp_path, capsys, "--explain", "--llm", "gemini", llm=llm)
    assert code == 0 and llm.calls == 1 and "generated by fake:m1" in out
    assert "in 900" in out and "out 120" in out
    code, out2, _ = run(tmp_path, capsys, "--explain", "--llm", "gemini", llm=llm)
    assert llm.calls == 1 and "cached" in out2.lower()          # second run is served from the cache: zero tokens


def test_llm_without_a_key_is_a_clear_error_not_a_crash(tmp_path, capsys, monkeypatch):
    for k in ("GOOGLE_API_KEY", "GEMINI_API_KEY"):
        monkeypatch.delenv(k, raising=False)
    code, out, err = run(tmp_path, capsys, "--llm", "gemini")
    assert code == 2 and "GOOGLE_API_KEY" in err


def test_html_report_gets_an_explanation_card_with_typed_claims_and_evidence(tmp_path, capsys):
    out_file = tmp_path / "r.html"
    code, out, err = run(tmp_path, capsys, "--explain", html=out_file)
    page = out_file.read_text(encoding="utf-8")
    m = re.search(r'<section[^>]*id="explanation".*?</section>', page, re.S)
    assert code == 0 and m
    s = m.group(0)
    assert 'class="badge fact"' in s and 'class="chip"' in s and "data-tip=" in s and "<details" in s and "<table" in s
    assert "generated by template" in s.lower()


def test_explanation_text_is_html_escaped(tmp_path, capsys):
    evil = NSE_CSV.replace("Reliance Industries Ltd.", "<script>alert(1)</script>")
    (tmp_path / "ind.csv").write_text(evil, encoding="utf-8")
    out_file = tmp_path / "r.html"
    f = tmp_path / "f.html"
    f.write_text(FILING_HTML, encoding="utf-8")
    code = main(["RELIANCE.NS", "--score", "--universe", str(tmp_path / "ind.csv"), "--explain", "--no-tej", "--html", str(out_file)],
                client=FakeClient(stmt=QUARTERLY, info=INFO2), sleep=lambda s: None, price_client=prices_for(SYMS))
    page = out_file.read_text(encoding="utf-8")
    assert code == 0 and "<script>alert(1)</script>" not in page
